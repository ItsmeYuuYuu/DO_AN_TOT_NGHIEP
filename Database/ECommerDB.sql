CREATE TABLE public.permissions (
    permissionid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(100) NOT NULL UNIQUE,
    name character varying(150) NOT NULL,
    groupname character varying(100) NOT NULL,
    description character varying(500)
);

CREATE TABLE public.userroles (
    userid integer NOT NULL,
    roleid integer NOT NULL,
    CONSTRAINT userroles_pkey PRIMARY KEY (userid, roleid),
    CONSTRAINT fk_userroles_users FOREIGN KEY (userid) REFERENCES public.users(userid) ON DELETE CASCADE,
    CONSTRAINT fk_userroles_roles FOREIGN KEY (roleid) REFERENCES public.roles(roleid) ON DELETE CASCADE
);

CREATE TABLE public.rolepermissions (
    roleid integer NOT NULL,
    permissionid integer NOT NULL,
    CONSTRAINT rolepermissions_pkey PRIMARY KEY (roleid, permissionid),
    CONSTRAINT fk_rolepermissions_roles FOREIGN KEY (roleid) REFERENCES public.roles(roleid) ON DELETE CASCADE,
    CONSTRAINT fk_rolepermissions_permissions FOREIGN KEY (permissionid) REFERENCES public.permissions(permissionid) ON DELETE CASCADE
);

CREATE INDEX "IX_userroles_roleid" ON public.userroles(roleid);
CREATE INDEX "IX_rolepermissions_permissionid" ON public.rolepermissions(permissionid);

